// Writes benchmark results into the "Benchmarks" section at the end of README.md.
// The section lives between two HTML comment markers; it is replaced in place when
// present and appended to the end of the README otherwise.
//
// Usage: BENCH_FORMAT=markdown bun run benchmark > bench.md
//        bun run ./scripts/update-readme-benchmark.ts bench.md

const README = 'README.md';
const START = '<!-- benchmark:start -->';
const END = '<!-- benchmark:end -->';

const fail = (message: string): never => {
	console.error(`error: ${message}`);
	process.exit(1);
};

const input = process.argv[2] ?? fail('usage: bun run ./scripts/update-readme-benchmark.ts <results.md>');
const results = (await Bun.file(input).text()).trim();
if (!results.includes('|')) fail(`${input} does not contain a markdown results table`);

// mitata prints "clk: / cpu: / runtime:" lines before the tables; turn them into a list
// so markdown doesn't fold them into a single paragraph.
const body = results
	.split('\n')
	.map((line) => line.replace(/^(clk|cpu|runtime): (.*)$/, '- **$1**: $2'))
	.join('\n');

const section = [
	START,
	'# Benchmarks',
	'',
	'Generated by CI on a GitHub-hosted runner, so absolute numbers vary between runs.',
	'Compare rows within a table rather than across runs.',
	'',
	body,
	END,
].join('\n');

const readme = await Bun.file(README).text();
const start = readme.indexOf(START);
const end = readme.indexOf(END);

let updated: string;
if (start !== -1 && end > start) {
	updated = readme.slice(0, start) + section + readme.slice(end + END.length);
} else if (start === -1 && end === -1) {
	updated = `${readme.trimEnd()}\n\n${section}\n`;
} else {
	updated = fail(`${README} has a malformed benchmark section (unmatched markers)`);
}

await Bun.write(README, updated);
console.log(`Updated benchmark section in ${README}`);
