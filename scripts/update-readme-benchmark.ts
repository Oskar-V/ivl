// Writes benchmark results into the "Benchmarks" section at the end of README.md.
// The section lives between two HTML comment markers; it is replaced in place when
// present and appended to the end of the README otherwise.
//
// Usage: BENCH_FORMAT=markdown bun run benchmark > bun.md
//        BENCH_FORMAT=markdown bun run benchmark:node > node.md
//        bun run ./scripts/update-readme-benchmark.ts bun.md node.md
// Each results file gets its own heading, named after the runtime mitata reports.

const README = 'README.md';
const START = '<!-- benchmark:start -->';
const END = '<!-- benchmark:end -->';
const CAVEATS_HEADING = '**Caveats**';

const fail = (message: string): never => {
	console.error(`error: ${message}`);
	process.exit(1);
};

const inputs = process.argv.slice(2);
if (!inputs.length) fail('usage: bun run ./scripts/update-readme-benchmark.ts <results.md>...');

const ENGINES: { [runtime: string]: string } = { bun: 'JavaScriptCore', node: 'V8', deno: 'V8' };

let caveats = '';
const sections: string[] = [];
for (const input of inputs) {
	const text = (await Bun.file(input).text()).trim();
	if (!text.includes('|')) fail(`${input} does not contain a markdown results table`);

	// The caveats are the same for every runtime, so they are printed once at the end
	const [results = '', caveats_text] = text.split(CAVEATS_HEADING);
	if (caveats_text && !caveats) caveats = `${CAVEATS_HEADING}\n${caveats_text.trimEnd()}`;

	const runtime = /^runtime: (\S+)/m.exec(results)?.[1] ?? fail(`${input} has no "runtime:" line`);
	const engine = ENGINES[runtime];
	const heading = `## ${runtime[0]!.toUpperCase()}${runtime.slice(1)}${engine ? ` (${engine})` : ''}`;

	// mitata prints "clk: / cpu: / runtime:" lines before the tables; turn them into a list
	// so markdown doesn't fold them into a single paragraph.
	const body = results
		.trim()
		.split('\n')
		.map((line) => line.replace(/^(clk|cpu|runtime): (.*)$/, '- **$1**: $2'))
		.join('\n');
	sections.push(`${heading}\n\n${body}`);
}

const section = [
	START,
	'# Benchmarks',
	'',
	'Generated by CI on a GitHub-hosted runner, so absolute numbers vary between runs.',
	'Compare rows within a table rather than across runs. Read the caveats at the end before',
	'drawing conclusions: the libraries do different amounts of work in some scenarios.',
	'',
	sections.join('\n\n'),
	...(caveats ? ['', caveats] : []),
	END,
].join('\n');

const readme = await Bun.file(README).text();
const start = readme.indexOf(START);
const end = readme.indexOf(END);

let updated: string;
if (start !== -1 && end > start) {
	updated = readme.slice(0, start) + section + readme.slice(end + END.length);
} else if (start === -1 && end === -1) {
	updated = `${readme.trimEnd()}\n\n${section}\n`;
} else {
	updated = fail(`${README} has a malformed benchmark section (unmatched markers)`);
}

await Bun.write(README, updated);
console.log(`Updated benchmark section in ${README}`);
